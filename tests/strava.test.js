test("every exercise in the library goes up as one of Strava's", () => {
  const lib = emptyData().exercises;
  for (const e of lib) {
    assert.ok(STRAVA_EXERCISE[e.id], `${e.name} has its Strava exercise`);
    assert.ok(STRAVA.has(STRAVA_EXERCISE[e.id]), `${e.name}: ${STRAVA_EXERCISE[e.id]} is one of Strava's`);
  }
  for (const id of Object.keys(STRAVA_EXERCISE)) assert.ok(lib.some((e) => e.id === id), `${id} is in the library`);
  // your own exercises: from the name, else the muscle; always one Strava knows
  const own = [["Pec deck", "Chest", "FLYE_GENERIC"], ["Machine row", "Back", "ROW_GENERIC"], ["Nordic curl", "Legs", "LEG_CURL_GENERIC"],
    ["Spider curl", "Biceps", "CURL_GENERIC"], ["Goblet squat", "Legs", "SQUAT_GENERIC"], ["Reverse lunge", "Legs", "LUNGE_GENERIC"],
    ["Donkey calf raise", "Legs", "CALF_RAISE_GENERIC"], ["Farmer's carry", "Other", "CARRY_GENERIC"], ["Tibialis thing", "Legs", "SQUAT_GENERIC"],
    ["Mystery", "Other", "TOTAL_BODY_GENERIC"], ["Neck harness", "Shoulders", "SHOULDER_PRESS_GENERIC"]];
  for (const [name, muscle, want] of own) assert.equal(stravaExercise(`ex-own-${name}`, { name, muscle }), want, name);
  for (const muscle of ["Back", "Chest", "Shoulders", "Biceps", "Triceps", "Legs", "Glutes", "Core", "Cardio", "Other"]) {
    assert.ok(STRAVA.has(stravaExercise("ex-own", { name: "Something", muscle })), muscle);
  }
});

test("the file Strava gets: every set, the start in UTC with the phone's offset, the length", () => {
  const data = emptyData();
  const start = new Date(2026, 10, 16, 17, 30).getTime();
  const session = { id: "s1", date: "2026-11-16", start, end: start + 3480000, dur: 3480, name: "Back", exercises: [
    { ex: "ex-lat-pulldown", name: "Lat pulldown", kind: "weight", muscle: "Back", sets: [{ w: 60, r: 10 }, { w: 62.5, r: 8 }] },
    { ex: "ex-pull-up", name: "Pull-up", kind: "reps", muscle: "Back", sets: [{ w: null, r: 8 }, { w: 10, r: 6 }] },
    { ex: "ex-plank", name: "Plank", kind: "time", muscle: "Core", sets: [{ s: 60 }, { s: 45 }] },
  ] };
  const f = stravaFile(session, data);
  assert.equal(f.version, "1.0");
  // UTC to the second: Strava can't read "+01:00" ("Error Processing Data")
  assert.equal(f.start_time, "2026-11-16T16:30:00Z");
  assert.match(f.start_time, /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$/);
  assert.equal(f.utc_offset, 3600);
  assert.equal(f.elapsed_time, 3480);
  assert.deepEqual(f.sets, [
    { exercise_type: "LAT_PULLDOWN", repetitions: 10, weight: 60 }, { exercise_type: "LAT_PULLDOWN", repetitions: 8, weight: 62.5 },
    { exercise_type: "PULL_UP_GENERIC", repetitions: 8 }, { exercise_type: "PULL_UP_GENERIC", repetitions: 6, weight: 10 },
    { exercise_type: "PLANK_GENERIC", duration: 60 }, { exercise_type: "PLANK_GENERIC", duration: 45 },
  ]);
  for (const s of f.sets) assert.ok(STRAVA.has(s.exercise_type));
  // summer time: the offset follows
  assert.equal(isoUtc(new Date(2026, 6, 1, 7, 5, 9, 450).getTime()), "2026-07-01T05:05:09Z");
  assert.equal(stravaFile({ ...session, start: new Date(2026, 6, 1, 7).getTime() }, data).utc_offset, 7200);
});

test("the description: the sets per muscle, then each exercise's sets", () => {
  const data = emptyData();
  const session = { id: "s2", start: Date.now(), dur: 3000, name: "Push", exercises: [
    { ex: "ex-bench-press", name: "Bench press", kind: "weight", muscle: "Chest", sets: [{ w: 80, r: 8 }, { w: 80, r: 8 }, { w: 77.5, r: 7 }] },
    { ex: "ex-lateral-raise", name: "Lateral raise", kind: "weight", muscle: "Shoulders", sets: [{ w: 10, r: 15 }, { w: 10, r: 12 }] },
    { ex: "ex-dips", name: "Dips", kind: "reps", muscle: "Chest", sets: [{ w: null, r: 12 }, { w: 10, r: 8 }] },
    { ex: "ex-treadmill", name: "Treadmill", kind: "time", muscle: "Cardio", sets: [{ s: 600 }] },
  ] };
  const muscles = musclesOf(session, data);
  assert.deepEqual(muscles.map((m) => m.muscle).slice(0, 2), ["Chest", "Shoulders"]);
  assert.ok(!muscles.some((m) => m.muscle === "Cardio"), "cardio counts no muscle");
  const text = stravaDescription(session, data);
  const lines = text.split("\n");
  assert.match(lines[0], /^Sets per muscle: Chest 5 · Shoulders /);
  assert.equal(lines[1], "");
  assert.equal(lines[2], "Bench press: 80 kg × 8, 8 · 77.5 kg × 7");
  assert.equal(lines[3], "Lateral raise: 10 kg × 15, 12");
  assert.equal(lines[4], "Dips: 12 reps · +10 kg × 8");
  assert.equal(lines[5], `Treadmill: ${setsText(session.exercises[3], "min")}`);
  assert.ok(!/\u00a0/.test(text), "plain spaces only");
  // the exercise's name as you have it in GymBro
  const renamed = applyOp(data, { type: "putExercise", exercise: { ...exerciseMap(data).get("ex-dips"), name: "Parallel bar dips" } });
  assert.match(stravaDescription(session, renamed), /^Parallel bar dips: /m);
});

